CREATE TABLE STAGIAIRES (
    ID_STAGIAIRE NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOM VARCHAR2(200) NOT NULL,
    PRENOM VARCHAR2(200) NOT NULL,
    EMAIL VARCHAR2(254) NOT NULL UNIQUE,
    TELEPHONE VARCHAR2(200) NOT NULL,
    ADRESSE VARCHAR2(200) NOT NULL,
    DATE_DE_NAISSANCE DATE NOT NULL,
    SEXE VARCHAR2(200) NOT NULL,
    CIN VARCHAR2(8) NOT NULL UNIQUE,
    NIVEAU VARCHAR2(200) NOT NULL
);
